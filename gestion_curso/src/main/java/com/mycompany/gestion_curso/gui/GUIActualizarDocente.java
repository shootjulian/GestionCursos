    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:

        int codigo;
        String nuevoNombre;
        double nuevoSalario;

        try{

            codigo = Integer.parseInt(txtCodigoDocente.getText().trim());
            nuevoNombre = txtNuevoNombre.getText().trim();
            nuevoSalario = Double.parseDouble(txtNuevoCosto.getText().trim());

            ServicioDocente.actualizarDocentePorCodigo(codigo, nuevoNombre, nuevoSalario);
            JOptionPane.showMessageDialog(this, "¡Docente actualizado!");

            // Cambiar los text fields con los nuevos atributos
            txtNombreActual.setText(nuevoNombre);
            txtSalarioDocente.setText(String.valueOf(nuevoSalario));

        } catch (Exception e){
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

