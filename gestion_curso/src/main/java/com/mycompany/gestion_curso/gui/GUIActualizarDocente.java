    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:

        int codigo;

        try{
            codigo = Integer.parseInt(txtCodigoDocente.getText().trim());

           Docente docente = ServicioDocente.buscarDocentePorCodigo(codigo);

            if (docente!=null){

                txtNombreActual.setText(docente.getNombre());

                if (docente.isPlanta()){
                    txtPlanta.setText("De Planta");
                } else{
                    txtPlanta.setText("No de Planta");
                }

                txtSalarioDocente.setText(String.valueOf(docente.getSalario()));

               txtEstadoDocente.setText(docente.getEstado().toUpperCase());

               

                btnActualizar.setEnabled(true);
            } else{
                JOptionPane.showMessageDialog(this, "¡Docente no encontrado!");
            }

        } catch (Exception e){
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

